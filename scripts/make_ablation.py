"""Ablation table of every method, built only from saved runs -> results/ABLATION.md,
and copied into docs/WRITEUP.md between <!-- ABLATION:START --> and <!-- ABLATION:END -->.

Methods were evaluated on different dev subsets (expensive ones on fewer segments), so each
row also shows the final iLQR and the linear MPC on the SAME segments for comparison.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
TIMING = json.load(open(R / "timing.json"))

# (label, dev csv, test csv or None, timing key or None, note)
ROWS = [
  ("PID (upstream baseline)", "runs/pid_10000-10499.csv", "runs/pid_00000-04999.csv", "pid", ""),
  ("PID + feedforward, Nelder-Mead", "runs/pid_ff_10000-10499.csv", "runs/pid_ff_00000-04999.csv", "pid_ff", ""),
  ("PID + feedforward, CMA-ES (strong baseline)", "runs/pid_ff_cma_10000-10499.csv", "runs/pid_ff_cma_00000-04999.csv", "pid_ff_cma", ""),
  ("LQR on ARX + observer (no preview)", "runs/lqr_10000-10499.csv", "runs/lqr_00000-04999.csv", "lqr", ""),
  ("MPC on ARX, no observer", "runs/mpc_noobs_10000-10499.csv", "runs/mpc_noobs_00000-04999.csv", "mpc_noobs", ""),
  ("MPC on ARX + observer, OSQP", "runs/mpc_10000-10499.csv", "runs/mpc_00000-04999.csv", "mpc", ""),
  ("MPC on ARX + observer, ADMM", "runs/mpc_admm_10000-10499.csv", "runs/mpc_admm_00000-04999.csv", "mpc_admm", ""),
  ("iLQR through TinyPhysics, first version", "runs/ilqr_noshifts_10000-10499.csv", "runs/ilqr_noshifts_00000-04999.csv", None, "blow-ups, see README"),
  ("iLQR through TinyPhysics (final)", "runs/ilqr_10000-10499.csv", "runs/ilqr_00000-04999.csv", "ilqr", ""),
  ("Risk-sensitive iLQR (+1.5 sigma^2, exact)", "runs/ilqr_rs_10000-10499.csv", "runs/ilqr_rs_00000-04999.csv", "ilqr_rs", ""),
  ("Expected-cost lookahead, one step (d=0)", "tuning/variance/lookahead_d0_10000-10199.csv", None, None, "negative result"),
  ("Expected-cost lookahead over the delay (d=3)", "tuning/variance/lookahead_d3_10000-10199.csv", None, "lookahead3", "negative result"),
  ("MPPI, independent per-step perturbations", "tuning/variance/mppi_v1.5_10000-10199.csv", None, None, "negative result"),
  ("MPPI, smooth (ramp) perturbations, + variance", "tuning/variance/mppi_ramp_v1.5_10000-10199.csv", None, "mppi", ""),
  ("MPPI, smooth perturbations, no variance term", "tuning/variance/mppi_ramp_v0_10000-10199.csv", None, None, ""),
  ("Linear MPC, horizon 8 (control for the hybrid MPC)", "hybrid/linear_mpc_H8_10000-10031.csv", None, None, ""),
  ("Hybrid-MPC code with the linear MPC's ARX (check)", "hybrid/hybrid_code_mpc_arx_10000-10031.csv", None, None, "must match the row above"),
  ("Hybrid-MPC code, speed-binned refit (1 mode/step)", "hybrid/hybrid_gcs_speedbins_10000-10031.csv", None, None, ""),
  ("Hybrid MPC on 8-region PWA, GCS relaxation + rounding", "hybrid/hybrid_gcs_pwa8_10000-10031.csv", None, "hybrid_gcs", "no test run (too slow)"),
]


def fmt_ms(ms):
  return f"{ms:.0f}" if ms >= 100 else f"{ms:.1f}" if ms >= 1 else f"{ms:.3f}" if ms >= 0.01 else f"{ms:.4f}"


def mean(path):
  d = pd.read_csv(R / path)
  return d, d[["lataccel_cost", "jerk_cost", "total_cost"]].mean()


def same_segments(ref, segs):
  d = pd.read_csv(R / f"runs/{ref}_10000-10499.csv", dtype={"seg": str})
  return d[d.seg.isin(segs)].total_cost.mean()


def main():
  lines = ["| method | dev segments | dev lataccel | dev jerk | dev total | iLQR, same segs | linear MPC, same segs | test total | ms/step | note |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
  for label, dev, test, tkey, note in ROWS:
    if not (R / dev).exists():
      continue
    d, m = mean(dev)
    segs = d.seg.astype(str).str.zfill(5)
    rng = f"{segs.min()}-{segs.max()} ({len(d)})"
    t = f"{mean(test)[1].total_cost:.2f}" if test and (R / test).exists() else ""
    ms = fmt_ms(TIMING[tkey]["ms_per_step"]) if tkey and tkey in TIMING else ""
    lines.append(f"| {label} | {rng} | {m.lataccel_cost:.3f} | {m.jerk_cost:.2f} | {m.total_cost:.2f} | "
                 f"{same_segments('ilqr', set(segs)):.2f} | {same_segments('mpc', set(segs)):.2f} | {t} | {ms} | {note} |")
  table = "\n".join(lines)
  header = ("# Ablation of every method\n\nGenerated by `scripts/make_ablation.py` from saved runs. Dev numbers are on "
            "the listed dev segments; the iLQR and linear-MPC columns are those controllers on the same segments. "
            "Test = the official 5000 segments, run once per final method. ms/step = update() time, one CPU thread "
            "(`results/timing.json`).\n\n")
  (R / "ABLATION.md").write_text(header + table + "\n")
  w = ROOT / "docs" / "WRITEUP.md"
  s = w.read_text()
  a, b = "<!-- ABLATION:START -->", "<!-- ABLATION:END -->"
  if a in s and b in s:
    s = s[:s.index(a) + len(a)] + "\n" + table + "\n" + s[s.index(b):]
    w.write_text(s)
  print(table)


if __name__ == "__main__":
  main()
