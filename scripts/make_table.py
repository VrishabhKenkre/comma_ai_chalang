"""Build results/RESULTS.md from the per-segment CSVs in results/runs/.

Numbers are never typed by hand: every row is the mean of a saved run.
Optional ms/step values come from results/timing.json (scripts/time_controllers.py).
"""
import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"


def main():
  timing_file = ROOT / "results" / "timing.json"
  timing = json.load(open(timing_file)) if timing_file.exists() else {}
  meta_file = RUNS / "batch_eval_meta.json"           # runs made with the lockstep evaluator
  batch_runs = json.load(open(meta_file)) if meta_file.exists() else {}
  rows = []
  for f in sorted(RUNS.glob("*.csv")):
    name, seg_range = f.stem.rsplit("_", 1)
    df = pd.read_csv(f)
    m = df[["lataccel_cost", "jerk_cost", "total_cost"]].mean()
    rows.append((seg_range, name, len(df), m.lataccel_cost, m.jerk_cost, m.total_cost,
                 timing.get(name, {}).get("ms_per_step"), "lockstep" if f.name in batch_runs else "official"))
  # test set first, then dev; within a set sort by total cost
  rows.sort(key=lambda r: (not r[0].startswith("00000"), r[0], -r[5]))
  lines = ["# Results", "",
           "Generated by `scripts/make_table.py` from `results/runs/*.csv`. "
           "Test set = segments 00000-04999 (the official eval set). "
           "Dev set = 10000-10499 (tuning used 10000-10199; disjoint from test). "
           "Evaluator: `official` = scripts/run_eval.py or eval.py (unmodified tinyphysics, one process per segment); "
           "`lockstep` = ctrl/batch_eval.py, checked to reproduce official per-segment costs exactly "
           "(results/batch_eval_verification.json). ms/step = controller update() time, single thread, "
           "from scripts/time_controllers.py.", "",
           "| segments | controller | n | lataccel_cost | jerk_cost | total_cost | ms/step | evaluator |",
           "|---|---|---:|---:|---:|---:|---:|---|"]
  for seg_range, name, n, la, jk, tot, ms, ev in rows:
    ms_s = f"{ms:.3g}" if ms is not None else ""
    lines.append(f"| {seg_range} | {name} | {n} | {la:.3f} | {jk:.3f} | {tot:.3f} | {ms_s} | {ev} |")
  lines += ["", "## Official eval.py reports (aggregate only)", "",
            "Parsed from `results/reports/report_<test>_vs_<baseline>_<n>.html` (unmodified eval.py).", "",
            "| report | controller | lataccel_cost | jerk_cost | total_cost |", "|---|---|---:|---:|---:|"]
  for f in sorted((ROOT / "results" / "reports").glob("report_*_vs_*.html")):
    test, base = f.stem[len("report_"):].rsplit("_", 1)[0].split("_vs_")
    for role, la, jk, tot in re.findall(r"<td>(test|baseline)</td>\s*<td>([\d.]+)</td>\s*<td>([\d.]+)</td>\s*<td>([\d.]+)</td>",
                                        f.read_text()):
      lines.append(f"| {f.name} | {test if role == 'test' else base} | {la} | {jk} | {tot} |")
  (ROOT / "results" / "RESULTS.md").write_text("\n".join(lines) + "\n")
  print("\n".join(lines))


if __name__ == "__main__":
  main()
