"""Build results/variance/VARIANCE.md from the saved step-1 runs (no numbers typed by hand)."""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
BASE_DEV200 = R / "tuning" / "ilqr_gpu_sweep" / "sweep_ilqr_H12_it1_w2.0_satshifts_10000-10199.csv"
DEV200 = [("risk-sensitive iLQR, variance weight 0.75", "rs_ilqr_v0.75_w2"),
          ("risk-sensitive iLQR, variance weight 1.5 (exact one-step expectation)", "rs_ilqr_v1.5_w2"),
          ("risk-sensitive iLQR, variance weight 3", "rs_ilqr_v3_w2"),
          ("risk-sensitive iLQR, weight 1.5, steer-rate weight 1 (not 2)", "rs_ilqr_v1.5_w1"),
          ("expected-cost lookahead, d = 0 (pure one-step)", "lookahead_d0"),
          ("expected-cost lookahead, d = 3 (spans the delay)", "lookahead_d3"),
          ("MPPI, iid perturbations, with variance term", "mppi_v1.5"),
          ("MPPI, iid perturbations, no variance term", "mppi_v0"),
          ("MPPI, ramp perturbations, 128 samples, 2 iterations, with variance term", "mppi_ramp_v1.5"),
          ("MPPI, ramp perturbations, 128 samples, 2 iterations, no variance term", "mppi_ramp_v0")]


def main():
  L = ["# Step 1: variance-aware control", "",
       "Generated by `scripts/summarize_variance.py` from saved runs. Costs are the official total cost.", ""]
  # 1a
  v = json.load(open(R / "variance" / "variance_vs_action.json"))
  L += ["## 1a. Does the steer action change the spread of the predicted distribution?", "",
        f"{v['n_points']} operating points from the final iLQR's closed-loop runs on dev {v['segs']}. "
        "The past is held fixed; the steer from step t on is set to u_t + delta (held), intermediate "
        "lataccels are expected values. Std and entropy of p(y_{t+k}) over the 1024 bins.", "",
        "| k | mean std at delta=0 | mean entropy at delta=0 | best variance reduction, abs(delta)<=0.1 (mean / median) | mean abs std change, abs(delta)<=0.1 | mean abs mean shift, abs(delta)<=0.1 | best variance reduction, abs(delta)<=0.3 |",
        "|---:|---:|---:|---:|---:|---:|---:|"]
  for k, row in v["by_k"].items():
    a, b = row["|delta|<=0.1"], row["|delta|<=0.3"]
    L.append(f"| {k} | {row['std_at_delta0_mean']:.4f} | {row['entropy_at_delta0_mean']:.3f} | "
             f"{100 * a['mean_rel_var_reduction']:.1f}% / {100 * a['median_rel_var_reduction']:.1f}% | "
             f"{a['mean_abs_std_change']:.4f} | {a['mean_abs_mean_shift']:.3f} | {100 * b['mean_rel_var_reduction']:.1f}% |")
  L += ["", "![spread vs steer change](variance_vs_action.png)", ""]
  # 1b dev 200
  base = pd.read_csv(BASE_DEV200).set_index("seg")
  L += ["## 1b. Variance-aware controllers on dev 10000-10199", "",
        f"Reference: final iLQR on the same segments, total {base.total_cost.mean():.3f}. "
        "Paired difference = mean over segments of (controller - iLQR), with its standard error.", "",
        "| controller | lataccel | jerk | total | median | paired diff vs iLQR |", "|---|---:|---:|---:|---:|---:|"]
  L.append(f"| final iLQR (reference) | {base.lataccel_cost.mean():.3f} | {base.jerk_cost.mean():.3f} | "
           f"{base.total_cost.mean():.3f} | {base.total_cost.median():.2f} | |")
  for label, name in DEV200:
    f = R / "tuning" / "variance" / f"{name}_10000-10199.csv"
    if not f.exists():
      continue
    d = pd.read_csv(f).set_index("seg")
    diff = (d.total_cost - base.total_cost).dropna()
    L.append(f"| {label} | {d.lataccel_cost.mean():.3f} | {d.jerk_cost.mean():.3f} | {d.total_cost.mean():.3f} | "
             f"{d.total_cost.median():.2f} | {diff.mean():+.3f} +- {diff.std() / np.sqrt(len(diff)):.3f} |")
  # noise floor
  nf = json.load(open(R / "noise_floor.json"))["summary"]
  L += ["", "## 1c. How much of the noise floor does it remove? (dev 10000-10099)", "",
        "Deterministic plant = the token nearest the expected value instead of a random draw (analysis only).", "",
        "| controller | stochastic (official) | deterministic | cost due to noise |", "|---|---:|---:|---:|"]
  rows = {"final iLQR": (nf["ilqr/stochastic"]["total_cost"], nf["ilqr/deterministic"]["total_cost"])}
  fs, fd = R / "noise_floor" / "ilqr_rs_stochastic_10000-10099.csv", R / "noise_floor" / "ilqr_rs_deterministic_10000-10099.csv"
  if fs.exists() and fd.exists():
    rows["risk-sensitive iLQR (weight 1.5)"] = (pd.read_csv(fs).total_cost.mean(), pd.read_csv(fd).total_cost.mean())
  for k, (s, d) in rows.items():
    L.append(f"| {k} | {s:.3f} | {d:.3f} | {s - d:.3f} |")
  if len(rows) == 2:
    (s0, d0), (s1, d1) = rows["final iLQR"], rows["risk-sensitive iLQR (weight 1.5)"]
    L += ["", f"Stochastic cost change: {s1 - s0:+.3f}, i.e. {100 * (s0 - s1) / (s0 - d0):.1f}% of the iLQR's "
          f"noise cost ({s0 - d0:.3f}) removed. Noise cost itself changes {(s1 - d1) - (s0 - d0):+.3f}."]
  # dev 500 and test
  L += ["", "## Dev 500 and the single test run", "", "| controller | segments | lataccel | jerk | total |", "|---|---|---:|---:|---:|"]
  for name, rng in [("ilqr", "10000-10499"), ("ilqr_rs", "10000-10499"), ("ilqr", "00000-04999"), ("ilqr_rs", "00000-04999")]:
    f = R / "runs" / f"{name}_{rng}.csv"
    if f.exists():
      d = pd.read_csv(f)
      L.append(f"| {name} | {rng} | {d.lataccel_cost.mean():.3f} | {d.jerk_cost.mean():.3f} | {d.total_cost.mean():.3f} |")
  for rng, label in [("10000-10499", "dev 500"), ("00000-04999", "test 5000")]:
    fa, fb = R / "runs" / f"ilqr_{rng}.csv", R / "runs" / f"ilqr_rs_{rng}.csv"
    if fa.exists() and fb.exists():
      a, b = pd.read_csv(fa).set_index("seg"), pd.read_csv(fb).set_index("seg")
      d = (b.total_cost - a.total_cost).dropna()
      L.append(f"\n{label}: paired difference (risk-sensitive - iLQR) {d.mean():+.3f} +- {d.std() / np.sqrt(len(d)):.3f}, "
               f"better on {(d < 0).sum()} of {len(d)} segments.")
  (R / "variance" / "VARIANCE.md").write_text("\n".join(L) + "\n")
  print("\n".join(L))


if __name__ == "__main__":
  main()
